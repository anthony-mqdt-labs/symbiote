//! zsh observation layer via ZDOTDIR redirection. The user's dotfiles are sourced,
//! never edited (WORKFLOW.md §6.1). Hooks are inert unless SYMBIOTE_ACTIVE=1.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

const SOURCE_USER: &str = r#"# Generated by symbiote. Sources your real config; never edits it.
if [[ "$ZDOTDIR" == "$SYMBIOTE_SHELL_DIR" ]]; then
  ZDOTDIR="${SYMBIOTE_USER_ZDOTDIR:-$HOME}"
  [[ -r "$ZDOTDIR/__FILE__" ]] && source "$ZDOTDIR/__FILE__"
  SYMBIOTE_USER_ZDOTDIR="$ZDOTDIR"
  ZDOTDIR="$SYMBIOTE_SHELL_DIR"
fi
"#;

const HOOKS: &str = r#"
# Restore the user's ZDOTDIR for history/compinit, then add observation hooks.
ZDOTDIR="${SYMBIOTE_USER_ZDOTDIR:-$HOME}"
if [[ "$SYMBIOTE_ACTIVE" == 1 && -x "$SYMBIOTE_BIN" ]]; then
  zmodload zsh/datetime 2>/dev/null
  typeset -g __symbiote_cmd="" __symbiote_t0=0
  __symbiote_preexec() { __symbiote_cmd="$1"; __symbiote_t0=$EPOCHREALTIME }
  __symbiote_precmd() {
    local ec=$? ps="${(j:,:)pipestatus}"
    [[ -z "$__symbiote_cmd" ]] && return
    local -i ms
    (( ms = (EPOCHREALTIME - __symbiote_t0) * 1000 ))
    "$SYMBIOTE_BIN" emit cmd_end --exit "$ec" --pipestatus "$ps" --duration "$ms" -- "$__symbiote_cmd" &>/dev/null &!
    __symbiote_cmd=""
  }
  autoload -Uz add-zsh-hook
  add-zsh-hook preexec __symbiote_preexec
  precmd_functions=(__symbiote_precmd ${precmd_functions:#__symbiote_precmd})
  # Layer 2 (optional): Neovim pushes LSP error counts. Skipped if you define your own nvim().
  if (( ! $+functions[nvim] )) && (( $+commands[nvim] )); then
    nvim() { command nvim --cmd 'lua pcall(dofile, vim.env.SYMBIOTE_SHELL_DIR .. "/symbiote.lua")' "$@" }
  fi
fi
"#;

/// Loaded via `nvim --cmd`, so the user's init.lua is untouched. Sends one NDJSON line to
/// symbiote.sock whenever a project buffer's LSP error count changes.
const NVIM_LUA: &str = r#"-- Generated by symbiote (Layer 2). Your Neovim config is never edited.
local sock, root = vim.env.SYMBIOTE_SOCK, vim.env.SYMBIOTE_ROOT
if vim.env.SYMBIOTE_ACTIVE ~= "1" or not sock or sock == "" or not root then return end
local uv = vim.uv or vim.loop
local last = {}
local function send(line)
  local pipe = uv.new_pipe(false)
  pipe:connect(sock, function(err)
    if err then return pipe:close() end
    pipe:write(line .. "\n", function() pipe:close() end)
  end)
end
vim.api.nvim_create_autocmd("DiagnosticChanged", {
  group = vim.api.nvim_create_augroup("symbiote_lsp_diag", { clear = true }),
  callback = function(args)
    local path = vim.api.nvim_buf_get_name(args.buf)
    if path:sub(1, #root + 1) ~= root .. "/" then return end
    local n = #vim.diagnostic.get(args.buf, { severity = vim.diagnostic.severity.ERROR })
    if last[path] == n then return end
    last[path] = n
    send(vim.json.encode({ type = "lsp_diag", path = path:sub(#root + 2), errors = n }))
  end,
})
"#;

/// Writes `.symbiote/shell/` and returns its path (the PTY's ZDOTDIR).
pub fn install(symbiote_dir: &Path) -> io::Result<PathBuf> {
    let dir = symbiote_dir.join("shell");
    fs::create_dir_all(&dir)?;
    for f in [".zshenv", ".zprofile", ".zlogin"] {
        fs::write(dir.join(f), SOURCE_USER.replace("__FILE__", f))?;
    }
    fs::write(dir.join(".zshrc"), format!("{}{HOOKS}", SOURCE_USER.replace("__FILE__", ".zshrc")))?;
    fs::write(dir.join("symbiote.lua"), NVIM_LUA)?;
    Ok(dir)
}
